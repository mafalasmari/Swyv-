// Copies the single-file build into the SWYV site, which serves it at /[lang]/app
// behind the mobile + code login (src/app/[lang]/app/route.ts).
import { readFileSync, writeFileSync } from "node:fs";

const html = readFileSync(new URL("../dist/index.html", import.meta.url), "utf8");
const out = new URL("../../src/lib/portal/app-html.ts", import.meta.url);
writeFileSync(out, `// Generated by portal/scripts/to-site.mjs (npm run build:site in portal/). Do not edit.\nexport const PORTAL_HTML = ${JSON.stringify(html)};\n`);
console.log(`portal → ${out.pathname} (${(html.length / 1024).toFixed(0)} kB)`);
